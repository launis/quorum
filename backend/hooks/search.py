"""Search hooks for executing external searches (e.g. Google)."""

import logging
from typing import List

from backend.exceptions import AppException, ErrorCodes
from backend.hooks.search_client import GoogleSearchTool, SearchResultItem as ClientSearchResultItem
from backend.models.domain.analyst import AnalystOutput, SearchResult, SearchResultItem
from backend.models.state import WorkflowState

logger = logging.getLogger(__name__)


def execute_google_search(state: WorkflowState) -> WorkflowState:
    """HOOK: execute_google_search.

    Executes Google Custom Search API based on hypotheses generated by the Analyst agent.

    Logic:
    1. Extracts 'search_query' from 'step_analyst.hypotheses'.
    2. Executes up to 3 queries using the Google Custom Search API.
    3. Stores results in 'context_variables.search_result' (Pydantic Model).

    Prerequisites:
        - Env vars: GOOGLE_SEARCH_API_KEY, GOOGLE_SEARCH_CX.
        - context_variables['step_analyst']: AnalystOutput.

    Args:
        state (WorkflowState): Current state containing analysis hypotheses.

    Returns:
        WorkflowState: Updated state with search results.

    Raises:
        AppException: If configuration is missing or execution fails.
    """
    logger.debug("[SearchHook] execute_google_search CALLED")

    # 1. Extract Analyst Output (Strict Type Check)
    step_analyst_data = state.context_variables.get("step_analyst")
    if not step_analyst_data:
        logger.warning("[SearchHook] 'step_analyst' not found in context. Skipping search.")
        return state

    try:
        if isinstance(step_analyst_data, dict):
            analyst_output = AnalystOutput(**step_analyst_data)
        elif isinstance(step_analyst_data, AnalystOutput):
            analyst_output = step_analyst_data
        else:
             logger.warning(f"[SearchHook] Invalid type for 'step_analyst': {type(step_analyst_data)}. Skipping.")
             return state
    except Exception as e:
        logger.error(f"[SearchHook] Failed to parse AnalystOutput: {e}")
        # Fail Fast? If we can't parse input, we can't search.
        # But maybe we shouldn't crash the whole workflow if just this hook fails?
        # Mandate says: "If an invalid state is detected, CRASH IMMEDIATELY."
        raise AppException(
            message=f"Invalid AnalystOutput data: {e}",
            status_code=500,
            details={"error_code": ErrorCodes.AGENT_SCHEMA_VALIDATION_FAILED}
        ) from e

    # 2. Extract Queries
    queries: List[str] = []
    if analyst_output.hypotheses:
        logger.debug(f"[SearchHook] Found {len(analyst_output.hypotheses)} hypotheses.")
        for hyp in analyst_output.hypotheses:
            if hyp.search_query and len(hyp.search_query.strip()) > 3:
                logger.debug(f"[SearchHook] Adding query: {hyp.search_query}")
                queries.append(hyp.search_query)
    else:
        logger.debug("[SearchHook] No hypotheses items found.")

    if not queries:
        logger.debug("[SearchHook] No valid queries generated. Skipping search.")
        return state

    # 3. Initialize Tool (Fails Fast on Config Error)
    try:
        tool = GoogleSearchTool()
    except Exception as e:
         # If queries exist but tool is broken -> CRITICAL ERROR
         raise

    # 4. Extract Language (Default: en)
    # Check context_variables first, then fallback (though context should have it)
    lang_code = state.context_variables.get("language", "en")
    
    # 5. Execute Search
    try:
        logger.debug(f"[SearchHook] Executing {len(queries)} searches (Lang: {lang_code})...")
        # tool.search returns List[ClientSearchResultItem]
        client_results = tool.search(queries, limit=3, language=str(lang_code))

        # Convert Client Model -> Domain Model
        domain_items: List[SearchResultItem] = []
        for r in client_results:
            domain_items.append(
                SearchResultItem(
                    title=r.title,
                    link=r.link,
                    snippet=r.snippet
                )
            )

        search_result = SearchResult(results=domain_items)

        # 5. Update State (Immutable)
        new_context = state.context_variables.copy()
        new_context["search_result"] = search_result
        
        # We enforce "search_result" as the specific key for SearchResult model.
        # We DO NOT populate legacy "aux_data" or "google_search_results" raw list 
        # unless strictly required by frontend. 
        # Checking walkthrough/legacy code: "google_search_results" might be used.
        # But "search_result" (SearchResult model) is the V2 standard.
        
        logger.debug(f"[SearchHook] Search complete. Found {len(domain_items)} results.")
        return state.model_copy(update={"context_variables": new_context})

    except Exception as e:
        # If tool.search failed, it probably raised proper AppException already.
        # If strict conversion failed, we catch it here.
        if isinstance(e, AppException):
            raise e
        
        error_code = ErrorCodes.SEARCH_EXECUTION_FAILED
        logger.error(f"[SearchHook] {error_code}: {e}", exc_info=True)
        raise AppException(
            message=f"Search hook execution failed: {e}",
            status_code=500,
            details={"error_code": error_code}
        ) from e
