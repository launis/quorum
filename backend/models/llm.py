from typing import Annotated, Any, Dict, List, Optional

from pydantic import BaseModel, Field


class LLMResponse(BaseModel):
    """
    Unified response wrapper for all LLM providers (Gemini 3, GPT-5.1, etc.).
    Supports advanced features like 'Meaning Tokens' (Thought Signature / Reasoning Blob).
    """

    content: Annotated[str, Field(description="The primary text content generated by the model.")]
    reasoning_token: Annotated[
        Optional[str],
        Field(
            default=None,
            description="Encrypted Blob representing the model's internal reasoning state (e.g. Gemini 'thought_signature' or OpenAI 'reasoning_blob'). Must be passed back to continue the thought process.",
        ),
    ]
    tool_calls: Annotated[
        Optional[List[Dict[str, Any]]],
        Field(default=None, description="List of tool use requests invoked by the model."),
    ]
    token_usage: Annotated[
        Dict[str, int], Field(default_factory=dict, description="Token usage statistics (prompt, completion, total).")
    ]
    provider_metadata: Annotated[
        Dict[str, Any],
        Field(default_factory=dict, description="Provider-specific raw metadata (e.g. finish_reason, safety_ratings)."),
    ]

    class Config:
        extra = "ignore"
