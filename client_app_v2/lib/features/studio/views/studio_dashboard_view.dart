    );
  }

  Widget _buildStepsTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    // ... Existing implementation of Steps Tab ...
    final blueprintsState = ref.watch(stepsControllerProvider);

    return SingleChildScrollView(
      padding: const EdgeInsets.all(16.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(context, l10n.studioViewsStepsTab, () {
            const StepNewRoute().go(context);
          }),
          const SizedBox(height: 16),
          blueprintsState.when(
            data: (blueprints) {
              if (blueprints.isEmpty)
                return Text(l10n.studioViewsNoStepsDefined);
              return ListView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                itemCount: blueprints.length,
                itemBuilder: (context, index) {
                  try {
                    final blueprint = blueprints[index];
                    final blueprintId = blueprint['id']?.toString();
                    if (blueprintId == null) {
                      throw AppException.validation(
                        'Blueprint step is corrupted: missing ID.',
                      );
                    }
                    final blocks = blueprint['prompt_blocks'] as List?;
                    if (blocks == null) {
                      throw AppException.validation(
                        'Blueprint prompt_blocks is missing for ID: $blueprintId',
                      );
                    }
                    final hooks = blueprint['pre_hooks'] as List?;
                    if (hooks == null) {
                      throw AppException.validation(
                        'Blueprint pre_hooks is missing for ID: $blueprintId',
                      );
                    }
                    final blockCount = blocks.length;
                    final hookCount = hooks.length;
                    final stepName = _getLocalizedName(
                      blueprint,
                      Localizations.localeOf(context).languageCode,
                    );

                    return Card(
                      child: ListTile(
                        title: Text(
                          stepName,
                          style: const TextStyle(fontWeight: FontWeight.bold),
                        ),
                        subtitle: Text(
                          '$blueprintId\n${l10n.studioViewsSlugSubtitle(blueprint['slug']?.toString() ?? '')}\n${l10n.studioViewsStepsSubtitle(blockCount, hookCount)}',
                        ),
                        trailing: Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            CloneEntityButton(
                              onClone: () async {
                                final id = blueprintId;
                                await ref
                                    .read(stepsControllerProvider.notifier)
                                    .cloneStep(id);
                              },
                            ),
                            const Icon(Icons.chevron_right),
                          ],
                        ),
                        onTap: () {
                          StepEditRoute($extra: blueprint).go(context);
                        },
                      ),
                    );
                  } catch (e) {
                    ref
                        .read(loggerServiceProvider)
                        .error(
                          'Studio',
                          'Error rendering step list tile: $e',
                          e,
                        );
                    return ErrorView(error: e, compact: true);
                  }
                },
              );
            },
            loading: () => const Center(child: CircularProgressIndicator()),
            error: (e, _) {
              return ErrorView(
                error: e,
                compact: true,
                onRetry: () =>
                    ref.read(stepsControllerProvider.notifier).refresh(),
              );
            },
          ),
        ],
      ),
    );
  }

  Widget _buildModelRegistryTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    final registryState = ref.watch(modelRegistryControllerProvider);

    return SingleChildScrollView(
      padding: const EdgeInsets.all(16.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(context, l10n.modelRegistryTitle, () {
            const ModelRegistryNewRoute().go(context);
          }),
          const SizedBox(height: 16),
          registryState.when(
            data: (configs) {
              if (configs.isEmpty) return Text(l10n.studioViewsNoSystemConfigs);
              return ListView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                itemCount: configs.length,
                itemBuilder: (context, index) {
                  try {
                    final config = configs[index];
                    final configId = config['id']?.toString();
                    if (configId == null) {
                      throw AppException.validation(
                        'Model Registry config is missing ID.',
                      );
                    }
                    final modelsMap = config['models'] as Map?;
                    if (modelsMap == null) {
                      throw AppException.validation(
                        'Model Registry models object is missing for ID: $configId',
                      );
                    }
                    final modelCount = modelsMap.length;

                    return Card(
                      child: ListTile(
                        title: Text(configId),
                        subtitle: Text(
                          l10n.studioViewsConfiguredModels(modelCount),
                        ),
                        trailing: Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            CloneEntityButton(
                              onClone: () async {
                                final id = configId;
                                await ref
                                    .read(
                                      modelRegistryControllerProvider.notifier,
                                    )
                                    .cloneConfig(id);
                              },
                            ),
                            const Icon(Icons.chevron_right),
                          ],
                        ),
                        onTap: () {
                          ModelRegistryEditRoute(
                            id: configId,
                            $extra: config,
                          ).go(context);
                        },
                      ),
                    );
                  } catch (e) {
                    ref
                        .read(loggerServiceProvider)
                        .error(
                          'Studio',
                          'Error rendering config list tile: $e',
                          e,
                        );
                    return ErrorView(error: e, compact: true);
                  }
                },
              );
            },
            loading: () => const Center(child: CircularProgressIndicator()),
            error: (e, _) {
              return ErrorView(
                error: e,
                compact: true,
                onRetry: () => ref
                    .read(modelRegistryControllerProvider.notifier)
                    .refresh(),
              );
            },
          ),
        ],
      ),
    );
  }

  Widget _buildSectionHeader(
    BuildContext context,
    String title,
    VoidCallback onAdd,
  ) {
    final l10n = AppLocalizations.of(context)!;
    return Row(
      mainAxisAlignment: MainAxisAlignment.spaceBetween,
      children: [
        Text(title, style: Theme.of(context).textTheme.titleLarge),
        FilledButton.icon(
          onPressed: onAdd,
          icon: const Icon(Icons.add),
          label: Text(l10n.studioViewsNewBtn),
        ),
      ],
    );
  }
}
