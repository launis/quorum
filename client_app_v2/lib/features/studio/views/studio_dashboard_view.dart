/// **Studio Dashboard View**
///
/// Main entry point for Admin users to manage Matrices and Workflows.
/// Uses `AsyncNotifierProvider` lists generated by `StudioController`.
class StudioDashboardView extends ConsumerStatefulWidget {
  const StudioDashboardView({super.key});

  @override
  ConsumerState<StudioDashboardView> createState() =>
      _StudioDashboardViewState();
}

class _StudioDashboardViewState extends ConsumerState<StudioDashboardView>
    with SingleTickerProviderStateMixin {
  late TabController _tabController;
  final TextEditingController _modelRegistrySearchController =
      TextEditingController();
  String _modelRegistrySearchQuery = '';

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 7, vsync: this);
  }

  @override
  void dispose() {
    _tabController.dispose();
    _modelRegistrySearchController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final l10n = AppLocalizations.of(context)!;

    return AppErrorBoundary(
      child: Scaffold(
        appBar: AppBar(
          leading: IconButton(
            icon: const Icon(Icons.arrow_back),
            tooltip: l10n.backToDashboard,
            onPressed: () => context.go('/dashboard'),
          ),
          title: Text(l10n.studioViewsAdminStudioV2),
          actions: [
            IconButton(
              icon: const Icon(Icons.refresh),
              tooltip: l10n.refresh,
              onPressed: () {
                ref.read(promptBlocksControllerProvider.notifier).refresh();
                ref.read(workflowsControllerProvider.notifier).refresh();
              },
            ),
          ],
          bottom: TabBar(
            controller: _tabController,
            isScrollable: true,
            tabs: [
              Tab(
                icon: const Icon(Icons.schema),
                text: l10n.studioDashboardWorkflowsTitle,
              ),
              Tab(
                icon: const Icon(Icons.chat),
                text: l10n.studioViewsPromptBlocksTab,
              ),
              Tab(
                icon: const Icon(Icons.dataset),
                text: l10n.studioDashboardMatricesTitle,
              ),
              Tab(
                icon: const Icon(Icons.extension),
                text: l10n.studioViewsStepsTab,
              ),
              Tab(
                icon: const Icon(Icons.print),
                text: l10n.studioViewsProfilesTab,
              ),
              Tab(
                icon: const Icon(Icons.settings),
                text: l10n.modelRegistryTitle,
              ),
              Tab(
                icon: const Icon(Icons.hub),
                text: l10n.studioDashboardGatewaysTitle,
              ),
            ],
          ),
        ),
        body: TabBarView(
          controller: _tabController,
          children: [
            const WorkflowsMasterView(),
            _buildRegularBlocksTab(context, ref, l10n),
            _buildMatricesTab(context, ref, l10n),
            _buildStepsTab(context, ref, l10n),
            _buildProfilesTab(context, ref, l10n),
            _buildModelRegistryTab(context, ref, l10n),
            const McpGatewaysMasterView(),
          ],
        ),
      ),
    );
  }

  Widget _buildProfilesTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    return const OutputProfileListView();
  }

  Widget _buildRegularBlocksTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    final promptBlocksState = ref.watch(promptBlocksControllerProvider);

    return SingleChildScrollView(
      padding: AppSpacing.p16,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(
            context,
            l10n.studioViewsPromptBlocksStandard,
            () async {
              try {
                final draft = await ref
                    .read(promptBlocksControllerProvider.notifier)
                    .createPromptBlockDraft();
                if (!context.mounted) return;
                PromptBlockEditRoute(
                  id: draft.id,
                  slug: draft.slug,
                ).go(context);
              } catch (e, st) {
                ref
                    .read(loggerServiceProvider)
                    .error(
                      'Studio',
                      'Failed to mint standard prompt block draft: $e',
                      e,
                      st,
                    );
                if (!context.mounted) return;
                ScaffoldMessenger.of(context).showSnackBar(
                  SnackBar(
                    content: Text(l10n.studioViewsMintDraftError(e.toString())),
                  ),
                );
              }
            },
          ),
          AppSpacing.h16,
          switch (promptBlocksState) {
            AsyncData(:final value) => () {
              final regularBlocks = value
                  .where(
                    (b) => !PromptBlockCategoryGroups.matrixCategories.contains(
                      b.categoryId,
                    ),
                  )
                  .toList();
              if (regularBlocks.isEmpty) {
                return Text(l10n.studioViewsNoStandardPromptBlocks);
              }
              return ListView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                itemCount: regularBlocks.length,
                itemBuilder: (context, index) {
                  try {
                    final block = regularBlocks[index];
                    final blockId = block.id.isNotEmpty
                        ? block.id
                        : (throw AppException.validation(
                            'PromptBlock ID is missing.',
                          ));
                    final slugStr = block.slug.isNotEmpty
                        ? block.slug
                        : (throw AppException.validation(
                            'PromptBlock slug is missing.',
                          ));
                    final blockName = block.label.get(
                      Localizations.localeOf(context).languageCode,
                    );

                    return Card(
                      child: ListTile(
                        leading: const Icon(Icons.text_snippet),
                        title: Text(
                          blockName,
                          overflow: TextOverflow.ellipsis,
                          style: Theme.of(context).textTheme.bodyLarge
                              ?.copyWith(fontWeight: FontWeight.bold),
                        ),
                        subtitle: Text(
                          '$blockId\n${l10n.studioViewsSlugSubtitle(slugStr)}',
                          overflow: TextOverflow.ellipsis,
                        ),
                        trailing: Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            CloneEntityButton(
                              onClone: () async {
                                final id = blockId;
                                await ref
                                    .read(
                                      promptBlocksControllerProvider.notifier,
                                    )
                                    .clonePromptBlock(id);
                              },
                            ),
                            const Icon(Icons.chevron_right),
                          ],
                        ),
                        onTap: () {
                          PromptBlockEditRoute(
                            id: blockId,
                            slug: slugStr,
                          ).go(context);
                        },
                      ),
                    );
                  } catch (e, st) {
                    ref
                        .read(loggerServiceProvider)
                        .error(
                          'Studio',
                          'Error rendering block list tile: $e',
                          e,
                          st,
                        );
                    return ErrorView(error: e, stackTrace: st, compact: true);
                  }
                },
              );
            }(),
            AsyncLoading() => const Center(child: CircularProgressIndicator()),
            AsyncError(:final error, :final stackTrace) => ErrorView(
              error: error,
              stackTrace: stackTrace,
              compact: true,
              onRetry: () =>
                  ref.read(promptBlocksControllerProvider.notifier).refresh(),
            ),
          },
        ],
      ),
    );
  }

  Widget _buildMatricesTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    final promptBlocksState = ref.watch(promptBlocksControllerProvider);

    return SingleChildScrollView(
      padding: AppSpacing.p16,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(
            context,
            l10n.studioDashboardMatricesTitle,
            () async {
              try {
                final draft = await ref
                    .read(promptBlocksControllerProvider.notifier)
                    .createPromptBlockDraft(
                      categoryId:
                          PromptBlockCategoryGroups.matrixCategories.first,
                    );
                if (!context.mounted) return;
                PromptBlockEditRoute(
                  id: draft.id,
                  slug: draft.slug,
                ).go(context);
              } catch (e, st) {
                ref
                    .read(loggerServiceProvider)
                    .error('Studio', 'Failed to mint matrix draft: $e', e, st);
                if (!context.mounted) return;
                ScaffoldMessenger.of(context).showSnackBar(
                  SnackBar(
                    content: Text(l10n.studioViewsMintDraftError(e.toString())),
                  ),
                );
              }
            },
          ),
          AppSpacing.h16,
          switch (promptBlocksState) {
            AsyncData(:final value) => () {
              final matrices = value
                  .where(
                    (b) => PromptBlockCategoryGroups.matrixCategories.contains(
                      b.categoryId,
                    ),
                  )
                  .toList();
              if (matrices.isEmpty) {
                return Text(l10n.studioViewsNoMatricesDefined);
              }
              return ListView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                itemCount: matrices.length,
                itemBuilder: (context, index) {
                  try {
                    final matrix = matrices[index];
                    final matrixId = matrix.id.isNotEmpty
                        ? matrix.id
                        : (throw AppException.validation(
                            'Matrix data is corrupted: missing ID.',
                          ));
                    final slugStr = matrix.slug.isNotEmpty
                        ? matrix.slug
                        : (throw AppException.validation(
                            'Matrix slug is missing.',
                          ));

                    final scalesList = matrix.scales;
                    final ruleCount = scalesList?.length ?? 0;
                    final matrixName = matrix.label.get(
                      Localizations.localeOf(context).languageCode,
                    );

                    return Card(
                      child: ListTile(
                        leading: const Icon(Icons.grid_on),
                        title: Text(
                          matrixName,
                          overflow: TextOverflow.ellipsis,
                          style: Theme.of(context).textTheme.bodyLarge
                              ?.copyWith(fontWeight: FontWeight.bold),
                        ),
                        subtitle: Text(
                          '$matrixId\n${l10n.matrixSubtitle(ruleCount)}',
                          overflow: TextOverflow.ellipsis,
                        ),
                        trailing: Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            CloneEntityButton(
                              onClone: () async {
                                final id = matrixId;
                                await ref
                                    .read(
                                      promptBlocksControllerProvider.notifier,
                                    )
                                    .clonePromptBlock(id);
                              },
                            ),
                            const Icon(Icons.chevron_right),
                          ],
                        ),
                        onTap: () {
                          PromptBlockEditRoute(
                            id: matrixId,
                            slug: slugStr,
                          ).go(context);
                        },
                      ),
                    );
                  } catch (e, st) {
                    ref
                        .read(loggerServiceProvider)
                        .error(
                          'Studio',
                          'Error rendering matrix list tile: $e',
                          e,
                          st,
                        );
                    return ErrorView(error: e, stackTrace: st, compact: true);
                  }
                },
              );
            }(),
            AsyncLoading() => const Center(child: CircularProgressIndicator()),
            AsyncError(:final error, :final stackTrace) => ErrorView(
              error: error,
              stackTrace: stackTrace,
              compact: true,
              onRetry: () =>
                  ref.read(promptBlocksControllerProvider.notifier).refresh(),
            ),
          },
        ],
      ),
    );
  }

  Widget _buildStepsTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    final blueprintsState = ref.watch(stepsControllerProvider);
    final currentScope = ref
        .watch(stepsControllerProvider.notifier)
        .currentScope;

    return SingleChildScrollView(
      padding: AppSpacing.p16,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(context, l10n.studioViewsStepsTab, () async {
            try {
              final draft = await ref
                  .read(stepsControllerProvider.notifier)
                  .createStepDraft();
              if (!context.mounted) return;
              StepEditRoute(id: draft.id).go(context);
            } catch (e, st) {
              ref
                  .read(loggerServiceProvider)
                  .error('Studio', 'Failed to mint step draft: $e', e, st);
              if (!context.mounted) return;
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(
                  content: Text(l10n.studioViewsMintDraftError(e.toString())),
                ),
              );
            }
          }),
          AppSpacing.h16,
          SegmentedButton<StepFilterScope>(
            segments: [
              ButtonSegment<StepFilterScope>(
                value: StepFilterScope.specialists,
                label: Text(l10n.studioStepFilterSpecialists),
                icon: const Icon(Icons.psychology_outlined),
              ),
              ButtonSegment<StepFilterScope>(
                value: StepFilterScope.systemCore,
                label: Text(l10n.studioStepFilterSystemCore),
                icon: const Icon(Icons.settings_suggest_outlined),
              ),
              ButtonSegment<StepFilterScope>(
                value: StepFilterScope.all,
                label: Text(l10n.studioStepFilterAll),
                icon: const Icon(Icons.view_list_outlined),
              ),
            ],
            selected: {currentScope},
            onSelectionChanged: (newSelection) {
              ref
                  .read(stepsControllerProvider.notifier)
                  .setScope(newSelection.first);
            },
          ),
          AppSpacing.h16,
          switch (blueprintsState) {
            AsyncData(:final value) => () {
              if (value.isEmpty) {
                return Text(l10n.studioViewsNoStepsDefined);
              }
              return ListView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                itemCount: value.length,
                itemBuilder: (context, index) {
                  try {
                    final blueprint = value[index];
                    final blueprintId = blueprint.id;
                    if (blueprintId.isEmpty) {
                      throw AppException.validation(
                        'Blueprint step is corrupted: missing ID.',
                      );
                    }

                    final stepName = blueprint.name.get(
                      Localizations.localeOf(context).languageCode,
                    );

                    final String typeLabel = switch (blueprint) {
                      NodeStrategyLogic() => '${l10n.type}: ${blueprint.hook}',
                      NodeStrategyLlm() =>
                        '${l10n.type}: ${blueprint.cognitiveTier.name}',
                      NodeStrategyCausalDiscovery() =>
                        '${l10n.type}: ${blueprint.engineType.name}',
                    };

                    return Card(
                      child: ListTile(
                        title: Text(
                          stepName,
                          overflow: TextOverflow.ellipsis,
                          style: Theme.of(context).textTheme.bodyLarge
                              ?.copyWith(fontWeight: FontWeight.bold),
                        ),
                        subtitle: Text(
                          '$blueprintId\n${l10n.studioViewsSlugSubtitle(blueprint.slug)}\n$typeLabel',
                          overflow: TextOverflow.ellipsis,
                        ),
                        trailing: Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            CloneEntityButton(
                              onClone: () async {
                                final id = blueprintId;
                                await ref
                                    .read(stepsControllerProvider.notifier)
                                    .cloneStep(id);
                              },
                            ),
                            const Icon(Icons.chevron_right),
                          ],
                        ),
                        onTap: () {
                          StepEditRoute(id: blueprintId).go(context);
                        },
                      ),
                    );
                  } catch (e, st) {
                    ref
                        .read(loggerServiceProvider)
                        .error(
                          'Studio',
                          'Error rendering step list tile: $e',
                          e,
                          st,
                        );
                    return ErrorView(error: e, stackTrace: st, compact: true);
                  }
                },
              );
            }(),
            AsyncLoading() => const Center(child: CircularProgressIndicator()),
            AsyncError(:final error, :final stackTrace) => ErrorView(
              error: error,
              stackTrace: stackTrace,
              compact: true,
              onRetry: () =>
                  ref.read(stepsControllerProvider.notifier).refresh(),
            ),
          },
        ],
      ),
    );
  }

  Widget _buildModelRegistryTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    final registryState = ref.watch(modelRegistryControllerProvider);

    return SingleChildScrollView(
      padding: AppSpacing.p16,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(context, l10n.modelRegistryTitle, () async {
            try {
              final draft = await ref
                  .read(modelRegistryControllerProvider.notifier)
                  .createSystemConfigDraft();
              if (!context.mounted) return;
              ModelRegistryEditRoute(id: draft.id).go(context);
            } catch (e, st) {
              ref
                  .read(loggerServiceProvider)
                  .error(
                    'Studio',
                    'Failed to mint system config draft: $e',
                    e,
                    st,
                  );
              if (!context.mounted) return;
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(
                  content: Text(l10n.studioViewsMintDraftError(e.toString())),
                ),
              );
            }
          }),
          AppSpacing.h16,
          switch (registryState) {
            AsyncData(:final value) => () {
              final query = _modelRegistrySearchQuery.trim().toLowerCase();
              final filteredConfigs = value.where((c) {
                if (query.isEmpty) return true;
                return c.name.toLowerCase().contains(query) ||
                    c.id.toLowerCase().contains(query) ||
                    c.defaultProvider.toLowerCase().contains(query) ||
                    (c.slug?.toLowerCase().contains(query) ?? false);
              }).toList();

              return Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  Row(
                    children: [
                      Expanded(
                        child: TextField(
                          controller: _modelRegistrySearchController,
                          decoration: InputDecoration(
                            prefixIcon: const Icon(Icons.search),
                            hintText: l10n.modelRegistrySearchPlaceholder,
                            border: const OutlineInputBorder(),
                            isDense: true,
                            suffixIcon: _modelRegistrySearchQuery.isNotEmpty
                                ? IconButton(
                                    icon: const Icon(Icons.clear),
                                    tooltip: l10n.studioMasterClearSearch,
                                    onPressed: () {
                                      _modelRegistrySearchController.clear();
                                      setState(() {
                                        _modelRegistrySearchQuery = '';
                                      });
                                    },
                                  )
                                : null,
                          ),
                          onChanged: (val) {
                            setState(() {
                              _modelRegistrySearchQuery = val;
                            });
                          },
                        ),
                      ),
                      AppSpacing.w12,
                      Chip(
                        avatar: const Icon(Icons.tune, size: 16),
                        label: Text(
                          '${filteredConfigs.length} / ${value.length}',
                        ),
                      ),
                    ],
                  ),
                  AppSpacing.h16,
                  if (filteredConfigs.isEmpty)
                    Padding(
                      padding: AppSpacing.p24,
                      child: Center(
                        child: Text(l10n.studioViewsNoSystemConfigs),
                      ),
                    )
                  else
                    ListView.builder(
                      shrinkWrap: true,
                      physics: const NeverScrollableScrollPhysics(),
                      itemCount: filteredConfigs.length,
                      itemBuilder: (context, index) {
                        try {
                          final config = filteredConfigs[index];
                          final configId = config.id;
                          if (configId.isEmpty) {
                            throw AppException.validation(
                              'Model Registry config is missing ID.',
                            );
                          }
                          final modelCount = config.tierDefinitions.length;

                          return Card(
                            margin: const EdgeInsets.only(
                              bottom: AppSpacing.s8,
                            ),
                            child: ListTile(
                              title: Text(
                                config.name.isNotEmpty ? config.name : configId,
                                overflow: TextOverflow.ellipsis,
                                style: Theme.of(context).textTheme.bodyLarge
                                    ?.copyWith(fontWeight: FontWeight.w600),
                              ),
                              subtitle: Padding(
                                padding: const EdgeInsets.only(
                                  top: AppSpacing.s4,
                                ),
                                child: Wrap(
                                  spacing: AppSpacing.s8,
                                  runSpacing: AppSpacing.s4,
                                  children: [
                                    Chip(
                                      visualDensity: VisualDensity.compact,
                                      label: Text(
                                        configId,
                                        style: Theme.of(
                                          context,
                                        ).textTheme.bodySmall,
                                      ),
                                    ),
                                    Chip(
                                      visualDensity: VisualDensity.compact,
                                      avatar: const Icon(Icons.cloud, size: 14),
                                      label: Text(
                                        config.defaultProvider.toUpperCase(),
                                        style: Theme.of(
                                          context,
                                        ).textTheme.bodySmall,
                                      ),
                                    ),
                                    Chip(
                                      visualDensity: VisualDensity.compact,
                                      avatar: const Icon(
                                        Icons.layers,
                                        size: 14,
                                      ),
                                      label: Text(
                                        l10n.studioViewsConfiguredModels(
                                          modelCount,
                                        ),
                                        style: Theme.of(
                                          context,
                                        ).textTheme.bodySmall,
                                      ),
                                    ),
                                  ],
                                ),
                              ),
                              trailing: Row(
                                mainAxisSize: MainAxisSize.min,
                                children: [
                                  CloneEntityButton(
                                    onClone: () async {
                                      final id = configId;
                                      await ref
                                          .read(
                                            modelRegistryControllerProvider
                                                .notifier,
                                          )
                                          .cloneConfig(id);
                                    },
                                  ),
                                  const Icon(Icons.chevron_right),
                                ],
                              ),
                              onTap: () {
                                ModelRegistryEditRoute(
                                  id: configId,
                                ).go(context);
                              },
                            ),
                          );
                        } catch (e, st) {
                          ref
                              .read(loggerServiceProvider)
                              .error(
                                'Studio',
                                'Error rendering config list tile: $e',
                                e,
                                st,
                              );
                          return ErrorView(
                            error: e,
                            stackTrace: st,
                            compact: true,
                          );
                        }
                      },
                    ),
                ],
              );
            }(),
            AsyncLoading() => const Center(child: CircularProgressIndicator()),
            AsyncError(:final error, :final stackTrace) => ErrorView(
              error: error,
              stackTrace: stackTrace,
              compact: true,
              onRetry: () =>
                  ref.read(modelRegistryControllerProvider.notifier).refresh(),
            ),
          },
        ],
      ),
    );
  }

  Widget _buildSectionHeader(
    BuildContext context,
    String title,
    VoidCallback onAdd,
  ) {
    final l10n = AppLocalizations.of(context)!;
    return Row(
      mainAxisAlignment: MainAxisAlignment.spaceBetween,
      children: [
        Expanded(
          child: Text(
            title,
            overflow: TextOverflow.ellipsis,
            style: Theme.of(context).textTheme.titleLarge,
          ),
        ),
        AppSpacing.w12,
        FilledButton.icon(
          onPressed: onAdd,
          icon: const Icon(Icons.add),
          label: Text(l10n.studioViewsNewBtn),
        ),
      ],
    );
  }
