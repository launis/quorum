/// **Studio Dashboard View**
///
/// Main entry point for Admin users to manage Matrices and Workflows.
/// Uses `AsyncNotifierProvider` lists generated by `StudioController`.
class StudioDashboardView extends ConsumerStatefulWidget {
  const StudioDashboardView({super.key});

  @override
  ConsumerState<StudioDashboardView> createState() =>
      _StudioDashboardViewState();
}

class _StudioDashboardViewState extends ConsumerState<StudioDashboardView>
    with SingleTickerProviderStateMixin {
  late TabController _tabController;

  String _getLocalizedName(dynamic entity, String currentLocale) {
    if (entity == null || entity is! Map) return 'Unknown';
    final nameVal = entity['name'] ?? entity['label'];
    if (nameVal is String) return nameVal;
    if (nameVal is Map) {
      final translations = nameVal['translations'];
      if (translations is Map) {
        if (translations[currentLocale] != null &&
            translations[currentLocale].toString().isNotEmpty) {
          return translations[currentLocale].toString();
        }
        final defaultLocale = nameVal['default_locale']?.toString() ?? 'en';
        if (translations[defaultLocale] != null &&
            translations[defaultLocale].toString().isNotEmpty) {
          return translations[defaultLocale].toString();
        }
      }
    }
    return entity['id']?.toString() ?? 'Unknown';
  }

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 7, vsync: this);
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final l10n = AppLocalizations.of(context)!;

    // Listen to tab changes to trigger refresh if desired
    // However, it's usually enough just to let the AsyncValue handle rebuilds.

    return Scaffold(
      appBar: AppBar(
        leading: IconButton(
          icon: const Icon(Icons.arrow_back),
          tooltip: 'Back to Application',
          onPressed: () => context.go('/dashboard'),
        ),
        title: Text(l10n.studioViewsAdminStudioV2),
        actions: [
          IconButton(
            icon: const Icon(Icons.refresh),
            onPressed: () {
              ref.read(promptBlocksControllerProvider.notifier).refresh();
              ref.read(workflowsControllerProvider.notifier).refresh();
            },
          ),
        ],
        bottom: TabBar(
          controller: _tabController,
          isScrollable: true,
          tabs: [
            Tab(
              icon: const Icon(Icons.schema),
              text: l10n.studioDashboardWorkflowsTitle,
            ),
            Tab(
              icon: const Icon(Icons.chat),
              text: l10n.studioViewsPromptBlocksTab,
            ),
            Tab(
              icon: const Icon(Icons.dataset),
              text: l10n.studioDashboardMatricesTitle,
            ),
            Tab(
              icon: const Icon(Icons.extension),
              text: l10n.studioViewsStepsTab,
            ),
            Tab(
              icon: const Icon(Icons.print),
              text: l10n.studioViewsProfilesTab,
            ),
            Tab(
              icon: const Icon(Icons.settings),
              text: l10n.modelRegistryTitle,
            ),
            Tab(
              icon: const Icon(Icons.hub),
              text: l10n.studioDashboardGatewaysTitle,
            ),
          ],
        ),
      ),
      body: TabBarView(
        controller: _tabController,
        children: [
          // TAB 1: Workflows
          const WorkflowsMasterView(),

          // TAB 2: Regular Prompt Blocks
          _buildRegularBlocksTab(context, ref, l10n),

          // TAB 3: Matrices (BARS)
          _buildMatricesTab(context, ref, l10n),

          // TAB 4: Steps
          _buildStepsTab(context, ref, l10n),

          // TAB 5: Profiles (Tulostusprofiilit)
          _buildProfilesTab(context, ref, l10n),

          // TAB 6: Model Registry
          _buildModelRegistryTab(context, ref, l10n),

          // TAB 7: MCP Gateways
          const McpGatewaysMasterView(),
        ],
      ),
    );
  }

  Widget _buildProfilesTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    return const OutputProfileListView();
  }

  Widget _buildRegularBlocksTab(
    BuildContext context,
    WidgetRef ref,
    AppLocalizations l10n,
  ) {
    final promptBlocksState = ref.watch(promptBlocksControllerProvider);

    return SingleChildScrollView(
      padding: const EdgeInsets.all(16.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildSectionHeader(
            context,
            l10n.studioViewsPromptBlocksStandard,
            () {
              const PromptBlockNewRoute().go(context);
            },
          ),
          const SizedBox(height: 16),
          promptBlocksState.when(
            data: (allBlocks) {
              final regularBlocks = allBlocks
                  .where((b) => b.categoryId != 'matrix')
                  .toList();
              if (regularBlocks.isEmpty)
                return Text(l10n.studioViewsNoStandardPromptBlocks);
              return ListView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                itemCount: regularBlocks.length,
                itemBuilder: (context, index) {
                  try {
                    final block = regularBlocks[index];
                    final blockId = block.id.isNotEmpty
                        ? block.id
                        : (throw AppException.validation(
                            'PromptBlock ID is missing.',
                          ));
                    final slugStr = block.slug.isNotEmpty
                        ? block.slug
                        : (throw AppException.validation(
                            'PromptBlock slug is missing.',
                          ));
                    final blockName = block.label.get(
                      Localizations.localeOf(context).languageCode,
                    );

                    return Card(
                      child: ListTile(
                        leading: const Icon(Icons.text_snippet),
                        title: Text(
                          blockName,
                          style: const TextStyle(fontWeight: FontWeight.bold),
                        ),
                        subtitle: Text(
                          '$blockId\n${l10n.studioViewsSlugSubtitle(slugStr)}',
                        ),
                        trailing: Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            CloneEntityButton(
                              onClone: () async {
                                final id = blockId;
                                await ref
                                    .read(
                                      promptBlocksControllerProvider.notifier,
                                    )
                                    .clonePromptBlock(id);
                              },
                            ),
                            const Icon(Icons.chevron_right),
                          ],
                        ),
                        onTap: () {
                          PromptBlockEditRoute(
                            id: blockId,
                            slug: slugStr,
                          ).go(context);
                        },
                      ),
                    );
                  } catch (e) {
                    ref
                        .read(loggerServiceProvider)
                        .error(
                          'Studio',
                          'Error rendering block list tile: $e',
                          e,
                        );
                    return ErrorView(error: e, compact: true);
                  }
                },
              );
            },
            loading: () => const Center(child: CircularProgressIndicator()),
            error: (e, _) => ErrorView(
              error: e,
              compact: true,
              onRetry: () =>
                  ref.read(promptBlocksControllerProvider.notifier).refresh(),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildMatricesTab(
    BuildContext context,
    WidgetRef ref,
